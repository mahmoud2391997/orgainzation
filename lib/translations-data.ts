export function getLocalizedService(service: Service, locale: "en" | "ar") {
  if (locale !== "ar") return service;
  const ar = arabicServices[service.id];
  if (!ar) return service;
  return {
    ...service,
    name: ar.name,
    description: ar.description,
    detailedDescription: ar.detailedDescription,
    offerings: ar.offerings ?? service.offerings,
    caseStudy: ar.caseStudy ?? service.caseStudy,
    caseMetric: ar.caseMetric ?? service.caseMetric,
  };
}

export function getLocalizedTechnology(tech: Technology, locale: "en" | "ar"): Technology & { support?: string[] } {
  const defaultSupportMap: Record<string, string[]> = {
    t1: ["AI & intelligent automation"],
    t2: ["Cloud, deployment & DevOps"],
    t3: ["AI & intelligent automation", "Software & web development"],
    t4: ["Software & web development"],
    t5: ["AI & intelligent automation", "API & systems integration"],
    t6: ["Cloud, deployment & DevOps", "Quality engineering & advisory"],
  };

  if (locale !== "ar") {
    return {
      ...tech,
      support: defaultSupportMap[tech.id] ?? [],
    };
  }
  const ar = arabicTechnologies[tech.id];
  if (!ar) {
    return {
      ...tech,
      support: defaultSupportMap[tech.id] ?? [],
    };
  }
  return {
    ...tech,
    name: ar.name,
    category: ar.category,
    description: ar.description,
    support: ar.support ?? defaultSupportMap[tech.id] ?? [],
  };
}

